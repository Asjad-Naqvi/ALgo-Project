"""C/D/E official LIFELINE master-release benchmark on data-derived prefixes.

Run from the project root after installing src/master_release.py:
    python3 -m benchmarks.benchmark_sameer_master --smoke
    python3 -m benchmarks.benchmark_sameer_master

The original master ZIP and its 20 checksums are verified before the run.
No synthetic inputs are generated by this module. Input sizes are official
case-table prefixes, documented in the output rows.
"""

import argparse
import csv
import multiprocessing as mp
import signal
import statistics
import time
import tracemalloc
from pathlib import Path

from src.master_release import load_master_release
from benchmarks.benchmark_sameer import (
    FIELDS, C_EXACT_LIMIT, LIMIT_SECONDS, count_ops, execute, _apply_edits,
)
from tests.reference_scheduling import exhaustive_scheduling
from src.huffman_coding import huffman_decode

C_SIZES = (16, 32, 64, 128, 256)
D_SIZES = (64, 128, 256, 512, 1024)
E_SIZES = (256, 512, 1024, 2048, 4096)
EDIT_SIZES = (16, 32, 64, 128, 256)
PATTERN_SIZES = (4, 8, 12, 20, 40)
CASE_C_D_EDIT = '1-40'
CASE_RADIO = '1-49'
DEFAULT_OUTPUT = Path('results/results_sameer_master_benchmarks.csv')


def tasks(smoke=False):
    specs = (
        ('C', 'scheduling', C_SIZES, ('greedy', 'weighted', 'exhaustive')),
        ('D', 'alarms', D_SIZES, ('heap', 'scan')),
        ('E', 'matching', E_SIZES, ('naive', 'kmp')),
        ('E', 'edit', EDIT_SIZES, ('full_dp', 'hirschberg')),
        ('E', 'compression', E_SIZES, ('huffman', 'fixed6')),
    )
    for module, experiment, sizes, algorithms in specs:
        for size in sizes[:1] if smoke else sizes:
            for algorithm in algorithms:
                yield module, experiment, algorithm, size


def extract_inputs(cases):
    """Materialize standard Python values once, before all timed operations."""
    large = cases[CASE_C_D_EDIT]
    trap = cases[CASE_RADIO]
    text = ''.join(
        row['text'] for row in sorted(trap.tables['radio_log'], key=lambda r: r['part'])
    )
    patterns = {len(row['pattern']): row['pattern']
                for row in trap.tables['radio_patterns']}
    report_rows = large.tables['radio_reports']
    if len(report_rows) != 1:
        raise AssertionError('Expected one report pair for case 1-40')
    report = (report_rows[0]['report_a'], report_rows[0]['report_b'])
    return {
        'windows': [dict(row) for row in large.tables['windows']],
        'incidents': [dict(row) for row in large.tables['incidents']],
        'radio_text': text,
        'patterns': patterns,
        'report': report,
    }


def make_official_input(inputs, experiment, size):
    if experiment == 'scheduling':
        rows = inputs['windows']
        if len(rows) < size:
            raise ValueError('Insufficient official windows')
        return rows[:size]
    if experiment == 'alarms':
        rows = inputs['incidents']
        if len(rows) < size:
            raise ValueError('Insufficient official alarms')
        return rows[:size]
    if experiment == 'matching':
        text = inputs['radio_text']
        pattern = inputs['patterns'].get(PATTERN_SIZES[E_SIZES.index(size)])
        if len(text) < size or not pattern:
            raise ValueError('Insufficient official radio input or pattern')
        return text[:size], pattern
    if experiment == 'edit':
        a, b = inputs['report']
        if len(a) < size or len(b) < size:
            raise ValueError('Insufficient official report length')
        return a[:size], b[:size]
    if experiment == 'compression':
        text = inputs['radio_text']
        if len(text) < size:
            raise ValueError('Insufficient official radio text')
        return text[:size]
    raise ValueError(f'Unknown experiment: {experiment}')


def instance_label(experiment):
    return {
        'scheduling': 'master_release_v1:1-40:windows:prefix',
        'alarms': 'master_release_v1:1-40:incidents:prefix',
        'matching': 'master_release_v1:1-49:radio_log:prefix',
        'edit': 'master_release_v1:1-40:radio_reports:prefix',
        'compression': 'master_release_v1:1-49:radio_log:prefix',
    }[experiment]


def check_correctness(experiment, data):
    """Check equivalent outputs or shared objective properties before timing."""
    if experiment == 'scheduling':
        greedy = execute(experiment, 'greedy', data)
        weighted = execute(experiment, 'weighted', data)
        for selection in (greedy, weighted):
            ordered = sorted(selection, key=lambda w: (w['start'], w['finish']))
            if any(a['finish'] > b['start'] for a, b in zip(ordered, ordered[1:])):
                raise AssertionError('Overlapping scheduled windows')
        if len(data) <= C_EXACT_LIMIT:
            count, value = exhaustive_scheduling(data)
            if len(greedy) != count or sum(w['value'] for w in weighted) != value:
                raise AssertionError('Scheduling reference disagreement')
    elif experiment == 'alarms':
        if execute(experiment, 'heap', data) != execute(experiment, 'scan', data):
            raise AssertionError('Queue algorithms disagree')
    elif experiment == 'matching':
        if execute(experiment, 'naive', data) != execute(experiment, 'kmp', data):
            raise AssertionError('Pattern matches disagree')
    elif experiment == 'edit':
        a, b = data
        full = execute(experiment, 'full_dp', data)
        linear = execute(experiment, 'hirschberg', data)
        if full[0] != linear[0]:
            raise AssertionError('Edit distances disagree')
        for distance, operations in (full, linear):
            if distance != len(operations) or _apply_edits(a, operations) != b:
                raise AssertionError('Edit reconstruction failed')
    elif experiment == 'compression':
        huff, book = execute(experiment, 'huffman', data)
        fixed, _ = execute(experiment, 'fixed6', data)
        if huffman_decode(huff, book) != data or len(huff) > len(fixed):
            raise AssertionError('Huffman roundtrip or payload check failed')


def _signal_timeout(_signum, _frame):
    raise TimeoutError(f'Exceeded {LIMIT_SECONDS}-second limit')


def _worker(send, experiment, algorithm, data):
    payload = {}
    signal.signal(signal.SIGALRM, _signal_timeout)
    signal.alarm(LIMIT_SECONDS)
    try:
        execute(experiment, algorithm, data)   # one discarded warmup
        timings = []
        for _ in range(5):
            start = time.perf_counter()
            execute(experiment, algorithm, data)
            timings.append(time.perf_counter() - start)
        tracemalloc.start()
        try:
            execute(experiment, algorithm, data)
            peak = tracemalloc.get_traced_memory()[1]
        finally:
            tracemalloc.stop()
        ops, unit = count_ops(experiment, algorithm, data)
        timings.sort()
        payload = {
            'status': 'OK',
            'time_s': f'{statistics.median(timings):.9f}',
            'time_iqr_s': f'{timings[3] - timings[1]:.9f}',
            'ops': ops,
            'mem_bytes': peak,
            'note': (f'ops_unit={unit}; input=master_release_v1_prefix; '
                     'warmup=1; measured=5; mem=tracemalloc_peak'),
        }
        if experiment == 'compression':
            huff, _ = execute('compression', 'huffman', data)
            saved = 100 * (1 - len(huff) / (6 * len(data)))
            payload['note'] += (f'; huffman_payload_bits={len(huff)}; '
                                f'fixed6_payload_bits={6 * len(data)}; '
                                f'payload_savings_pct={saved:.2f}; excludes_codebook')
    except TimeoutError:
        payload = {'status': 'DNF', 'note': f'actual {LIMIT_SECONDS}s timeout'}
    except Exception as exc:
        payload = {'status': 'ERROR', 'note': f'{type(exc).__name__}: {exc}'}
    finally:
        signal.alarm(0)
        send.send(payload)
        send.close()


def run_task(task, data):
    module, experiment, algorithm, size = task
    row = dict.fromkeys(FIELDS, '')
    row.update(module=module, experiment=experiment, algorithm=algorithm,
               instance=instance_label(experiment), size=size,
               size2=(len(data[1]) if experiment == 'matching' else
                      len(data[1]) if experiment == 'edit' else ''))
    if experiment == 'scheduling' and algorithm == 'exhaustive' and size > C_EXACT_LIMIT:
        row.update(status='DNF', note=(f'predefined exact cap n>{C_EXACT_LIMIT}; '
                                       'not a timeout; official master prefix'))
        return row
    ctx = mp.get_context('spawn')
    recv, send = ctx.Pipe(duplex=False)
    proc = ctx.Process(target=_worker, args=(send, experiment, algorithm, data))
    proc.start()
    send.close()
    proc.join(LIMIT_SECONDS + 10)
    if proc.is_alive():
        proc.terminate()
        proc.join()
        row.update(status='DNF', note='forced termination after experiment limit')
    elif recv.poll():
        row.update(recv.recv())
    else:
        row.update(status='ERROR', note=f'worker exitcode={proc.exitcode}; no result')
    recv.close()
    return row


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path,
                        default=Path.home() / 'Downloads' / 'archive.zip')
    parser.add_argument('--out', type=Path, default=None)
    parser.add_argument('--smoke', action='store_true')
    args = parser.parse_args()
    output = args.out or (Path('results/results_sameer_master_smoke.csv')
                          if args.smoke else DEFAULT_OUTPUT)
    case_ids = (CASE_C_D_EDIT, CASE_RADIO)
    print('Verifying ZIP checksums and reading official source cases ...', flush=True)
    cases = load_master_release(args.archive, case_ids)
    inputs = extract_inputs(cases)
    planned = list(tasks(args.smoke))
    output.parent.mkdir(parents=True, exist_ok=True)
    checked = set()
    with output.open('w', encoding='utf-8', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS)
        writer.writeheader()
        for index, task in enumerate(planned, 1):
            _module, experiment, algorithm, size = task
            data = make_official_input(inputs, experiment, size)
            if (experiment, size) not in checked:
                check_correctness(experiment, data)
                checked.add((experiment, size))
            result = run_task(task, data)
            writer.writerow(result)
            stream.flush()
            print(f'{index:02d}/{len(planned)} {experiment:<12} '
                  f'n={size:<5} {algorithm:<11} {result["status"]}', flush=True)
    print(f'Wrote {output}')


if __name__ == '__main__':
    main()
